/** De catalogus als compacte tekst voor de AI-prompt. */
export function buildExerciseCatalogText(): string {
  return Object.entries(GARMIN_EXERCISE_CATALOG)
    .map(([category, names]) => `${category}: ${names.join(', ')}`)
    .join('\n');
}

/** Bestaat deze code ("PLANK/SIDE_PLANK") in de geverifieerde catalogus? */
export function isKnownExerciseCode(code: string): boolean {
  const [category, name] = String(code).split('/');
  return Boolean(category && name && GARMIN_EXERCISE_CATALOG[category]?.includes(name));
}
